CommandBuffer::CommandBuffer(CommandScheduler& scheduler)
    : m_context(scheduler.Context()), m_graphics(scheduler.Graphics()) {}

void CommandBuffer::Begin() {
	EXIT_IF(m_rendering || IsInvalid());
	m_dispatch_barrier_pending = false;
	auto buffer = Handle();

	vk::CommandBufferBeginInfo begin_info {};
	begin_info.flags = vk::CommandBufferUsageFlagBits::eOneTimeSubmit;

	auto result = buffer.begin(&begin_info);

	EXIT_NOT_IMPLEMENTED(result != vk::Result::eSuccess);
}

void CommandBuffer::End() const {
	EndRendering();
	auto buffer = Handle();

	auto result = buffer.end();

	EXIT_NOT_IMPLEMENTED(result != vk::Result::eSuccess);
}

void CommandBuffer::RecordDispatchBarrier() const noexcept {
	m_dispatch_barrier_pending = false;
	RecordDispatchBarrierOn(m_buffer);
}

void CommandBuffer::RecordDispatchBarrierOn(vk::CommandBuffer cb) noexcept {
	ShaderAccessBarrier(cb, vk::PipelineStageFlagBits::eComputeShader);
}

static void RecordBeginRendering(vk::CommandBuffer buffer, const RenderState& state) {
	std::array<vk::RenderingAttachmentInfo, RENDER_COLOR_ATTACHMENTS_MAX> colors {};
	for (uint32_t i = 0; i < state.num_color_attachments; i++) {
		const auto& attachment = state.color_attachments[i];
		colors[i].imageView    = attachment.image_view;
		colors[i].imageLayout  = attachment.image_layout;
		colors[i].loadOp       = vk::AttachmentLoadOp::eLoad;
		colors[i].storeOp      = vk::AttachmentStoreOp::eStore;
	}

	const auto&                 depth_stencil = state.depth_stencil_attachment;
	vk::RenderingAttachmentInfo depth {};
	depth.imageView   = depth_stencil.image_view;
	depth.imageLayout = depth_stencil.image_layout;
	depth.loadOp =
	    depth_stencil.depth_clear ? vk::AttachmentLoadOp::eClear : vk::AttachmentLoadOp::eLoad;
	// An aspect the layout keeps read-only has nothing to store: STORE_OP_NONE keeps the
	// attachment a read, so sampling it alongside needs no barrier.
	depth.storeOp = DepthReadOnly(depth_stencil.image_layout) ? vk::AttachmentStoreOp::eNone
	                                                          : vk::AttachmentStoreOp::eStore;
	depth.clearValue.depthStencil.depth = std::bit_cast<float>(depth_stencil.clear_value[0]);

	vk::RenderingAttachmentInfo stencil {};
	stencil.imageView   = depth_stencil.image_view;
	stencil.imageLayout = depth_stencil.image_layout;
	stencil.loadOp =
	    depth_stencil.stencil_clear ? vk::AttachmentLoadOp::eClear : vk::AttachmentLoadOp::eLoad;
	stencil.storeOp = StencilReadOnly(depth_stencil.image_layout) ? vk::AttachmentStoreOp::eNone
	                                                              : vk::AttachmentStoreOp::eStore;
	stencil.clearValue.depthStencil.stencil = depth_stencil.clear_value[1];

	vk::RenderingInfo rendering {};
	rendering.renderArea.extent    = {state.width, state.height};
	rendering.layerCount           = state.num_layers;
	rendering.colorAttachmentCount = state.num_color_attachments;
	rendering.pColorAttachments    = colors.data();
	rendering.pDepthAttachment     = depth_stencil.has_depth ? &depth : nullptr;
	rendering.pStencilAttachment   = depth_stencil.has_stencil ? &stencil : nullptr;
	buffer.beginRendering(rendering);
}

void CommandBuffer::BeginRendering(const RenderState& state) const {
	if (m_rendering && m_render_state == state) {
		return;
	}
	// Queued like the draw that follows: the pass switch needs no wait for the recording thread.
	const bool end = m_rendering;
	Record([end, state](vk::CommandBuffer buffer) {
		if (end) {
			buffer.endRendering();
		}
		RecordBeginRendering(buffer, state);
	});
	m_render_state = state;
	// The open pass holds the cleared contents, so a later clear begins a new pass.
	m_render_state.depth_stencil_attachment.depth_clear   = false;
	m_render_state.depth_stencil_attachment.stencil_clear = false;
	m_rendering                                           = true;
}

void CommandBuffer::EndRendering() const {
	if (!m_rendering) {
		return;
	}
	RecordQueued([](vk::CommandBuffer cb) { cb.endRendering(); });
	m_rendering = false;
}

